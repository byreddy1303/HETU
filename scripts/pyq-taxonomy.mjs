const subjectBySlug = new Map(PYQ_TAXONOMY.map((subject) => [subject.slug, subject]));

function result(subjectSlug, topicSlug, basis) {
  const subject = subjectBySlug.get(subjectSlug);
  const topic = subject?.topics.find((item) => item.slug === topicSlug);
  if (!subject || !topic) throw new Error(`Unknown PYQ classification ${subjectSlug}/${topicSlug}`);
  return {
    subject: subject.label,
    subjectSlug,
    topic: topic.label,
    topicSlug,
    classificationBasis: basis
  };
}

function contextFor(question) {
  const orderedTags = (question.subtopics ?? []).map((tag) => String(tag).toLowerCase());
  const tags = new Set(orderedTags);
  const html = String(question.html ?? '')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&[a-z]+;/gi, ' ')
    .replace(/\s+/g, ' ')
    .toLowerCase();
  const has = (...values) => values.some((value) => tags.has(value));
  const hasPart = (...values) =>
    values.some((value) => [...tags].some((tag) => tag.includes(value)));
  const text = (pattern) => pattern.test(html);
  return { orderedTags, tags, html, has, hasPart, text };
}

