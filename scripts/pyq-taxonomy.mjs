function inferredSubjectSlug(question, ctx) {
  if (ctx.text(/young tableau/)) return 'data-structure';
  for (const tag of ctx.orderedTags) {
    const subjectSlug = SUBJECT_BY_TAG.get(tag);
    if (subjectSlug) return subjectSlug;
  }
  return question.subjectSlug;
}

function firstMappedTag(ctx, entries) {
  const map = new Map(entries);
  for (const tag of ctx.orderedTags) {
    const topicSlug = map.get(tag);
    if (topicSlug) return topicSlug;
  }
  return null;
}

