function classifyProgramming(ctx) {
  const dataStructureTags = [
    'data-structures',
    'abstract-data-type',
    'linked-list',
    'stack',
    'queue',
    'binary-tree',
    'binary-search-tree',
    'avl-tree',
    'b-tree',
    'heap',
    'binary-heap',
    'hashing',
    'priority-queue',
    'tree',
    'tree-traversal'
  ];
  if (ctx.has(...dataStructureTags)) return classifyDataStructure(ctx);
  const firstTopic = firstMappedTag(ctx, [
    ['pointers', 'array-and-pointer'],
    ['array', 'array-and-pointer'],
    ['strings', 'array-and-pointer'],
    ['structure', 'array-and-pointer'],
    ['recursion', 'function'],
    ['functions', 'function'],
    ['parameter-passing', 'function'],
    ['loop-invariants', 'loops']
  ]);
  if (firstTopic) return result('c-programming', firstTopic, 'ordered-topic-tag');
  if (ctx.hasPart('pointer', 'array', 'string', 'structure'))
    return result('c-programming', 'array-and-pointer', 'topic-rule');
  if (ctx.hasPart('recursion', 'function', 'parameter-passing'))
    return result('c-programming', 'function', 'topic-rule');
  if (ctx.hasPart('loop', 'invariant') || ctx.text(/\bfor\s*\(|\bwhile\s*\(/))
    return result('c-programming', 'loops', 'topic-rule');
  if (ctx.text(/\bif\s*\(|\bswitch\s*\(|conditional operator/))
    return result('c-programming', 'conditional-statement', 'topic-rule');
  return result('c-programming', 'arithmetic-operation', 'topic-rule');
}

