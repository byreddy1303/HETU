export function classifyPyqQuestion(question) {
  const ctx = contextFor(question);
  const subjectSlug = inferredSubjectSlug(question, ctx);
  switch (subjectSlug) {
    case 'general-aptitude':
      return result('general-aptitude', 'general-aptitude', 'subject-rule');
    case 'discrete-mathematics':
      return classifyDiscrete(ctx);
    case 'engineering-mathematics':
      return classifyEngineering(ctx);
    case 'digital-logic':
      return classifyDigitalLogic(ctx);
    case 'coa':
      return classifyCoa(ctx);
    case 'programming-and-ds':
    case 'c-programming':
    case 'data-structure':
      return subjectSlug === 'data-structure'
        ? classifyDataStructure(ctx)
        : classifyProgramming(ctx);
    case 'algorithms':
      return classifyAlgorithms(ctx);
    case 'theory-of-computation':
      return classifyToc(ctx);
    case 'compiler-design':
      return classifyCompiler(ctx);
    case 'operating-systems':
      return classifyOs(ctx);
    case 'databases':
      return classifyDatabases(ctx);
    case 'computer-networks':
      return classifyNetworks(ctx);
    case 'other-optional':
      return classifyOptional(ctx);
    default:
      throw new Error(`No classifier for PYQ subject ${subjectSlug}`);
  }
}

